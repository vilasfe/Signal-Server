    TEST(TestHZNS, HZNS) {
        struct prop_type prop = {};

        std::array<double, 160> pfl = {
            156, 498.71794871794873, 96, 84, 65, 46, 46, 46, 61,
            41, 33, 27, 23, 19, 15, 15, 15, 15, 15, 15, 15, 15, 15,
            15, 15, 15, 17, 19, 21, 23, 25, 27, 29, 35, 46, 41, 35,
            30, 33, 35, 37, 40, 35, 30, 51, 62, 76, 46, 46, 46, 46,
            46, 46, 50, 56, 67, 106, 83, 95, 112, 137, 137, 76, 103,
            122, 122, 83, 71, 61, 64, 67, 71, 74, 77, 79, 86, 91,
            83, 76, 68, 63, 76, 107, 107, 107, 119, 127, 133, 135,
            137, 142, 148, 152, 152, 107, 137, 104, 91, 99, 120, 152,
            152, 137, 168, 168, 122, 137, 137, 170, 183, 183, 187,
            194, 201, 192, 152, 152, 166, 177, 198, 156, 127, 116,
            107, 104, 101, 98, 95, 103, 91, 97, 102, 107, 107, 107,
            103, 98, 94, 91, 105, 122, 122, 122, 122, 122, 137, 137,
            137, 137, 137, 137, 137, 137, 140, 144, 147, 150, 152, 159
        };

        prop.dist = 77800; // distance in meters
        prop.hg = {143.9, 8.5};
        prop.gme = 1.1480007964369815e-07;

        itm_math::hzns_unopt(std::span(pfl), prop);

        // Test horizon takeoff angle
        EXPECT_NEAR(prop.the[0], -0.0039, 1e-4);
        EXPECT_NEAR(prop.the[1], 0.0005, 1e-4);

        // Test horizon distances
        EXPECT_NEAR(prop.dl[0], 55357.6923, 1e-4);
        EXPECT_NEAR(prop.dl[1], 19450.0000, 1e-4);

        itm_math::hzns2(std::span(pfl), prop);

        // Test horizon takeoff angle
        EXPECT_NEAR(prop.the[0], -0.0039, 1e-4);
        EXPECT_NEAR(prop.the[1], 0.0005, 1e-4);

        // Test horizon distances
        EXPECT_NEAR(prop.dl[0], 55357.6923, 1e-4);
        EXPECT_NEAR(prop.dl[1], 19450.0000, 1e-4);

        itm_math::hzns(std::span(pfl), prop);

        // Test horizon takeoff angle
        EXPECT_NEAR(prop.the[0], -0.0039, 1e-4);
        EXPECT_NEAR(prop.the[1], 0.0005, 1e-4);

        // Test horizon distances
        EXPECT_NEAR(prop.dl[0], 55357.6923, 1e-4);
        EXPECT_NEAR(prop.dl[1], 19450.0000, 1e-4);
    }

